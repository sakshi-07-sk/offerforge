const puppeteer = require('puppeteer-core');
const chromium = require('@sparticuz/chromium');

const generatePdf = async (htmlContent) => {
  // Configured for Firebase Cloud Functions environment
  const executablePath = await chromium.executablePath();
  
  const browser = await puppeteer.launch({
    args: chromium.args,
    defaultViewport: chromium.defaultViewport,
    executablePath,
    headless: chromium.headless,
  });
  
  const page = await browser.newPage();
  
  const fullHtml = `
    <!DOCTYPE html>
    <html>
      <head>
        <style>
          body { font-family: 'Helvetica Neue', Helvetica, Arial, sans-serif; color: #333; margin: 40px; }
          .header { text-align: center; border-bottom: 2px solid #14b8a6; padding-bottom: 20px; margin-bottom: 30px; }
          .footer { text-align: center; font-size: 12px; color: #777; margin-top: 50px; border-top: 1px solid #eee; padding-top: 20px; }
          .content { line-height: 1.6; font-size: 14px; }
        </style>
      </head>
      <body>
        <div class="header">
          <h1>Offer Letter</h1>
        </div>
        <div class="content">
          ${htmlContent}
        </div>
        <div class="footer">
          <p>Generated by Offer Letter Builder System</p>
        </div>
      </body>
    </html>
  `;
  
  await page.setContent(fullHtml, { waitUntil: 'networkidle0' });
  
  const pdfBuffer = await page.pdf({
    format: 'A4',
    printBackground: true,
    margin: { top: '20px', right: '20px', bottom: '20px', left: '20px' }
  });
  
  await browser.close();
  return pdfBuffer;
};

module.exports = { generatePdf };
